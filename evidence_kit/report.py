def _now() -> str:
    sde = os.environ.get("SOURCE_DATE_EPOCH")
    t = (
        dt.datetime.fromtimestamp(int(sde), dt.timezone.utc)
        if sde and sde.isdigit()
        else dt.datetime.now(dt.timezone.utc)
    )
    return t.replace(microsecond=0).isoformat()


def file_hashes(directory: Path) -> list[dict[str, Any]]:
    out = []
    for p in sorted(Path(directory).rglob("*")):
        if not p.is_file() or p.name in OWN_OUTPUTS:
            continue
        data = p.read_bytes()
        out.append(
            {
                "path": p.relative_to(directory).as_posix(),
                "sha256": hashlib.sha256(data).hexdigest(),
                "bytes": len(data),
            }
        )
    return out


def build(evidence_dir: Path, mapping: dict[str, Any]) -> dict[str, Any]:
    ev = Evidence.load(Path(evidence_dir))
    meta = (ev.get("repo") or {}).get("meta") or {}
    controls = []
    for c in mapping["controls"]:
        entry: dict[str, Any] = {
            "id": c["id"],
            "mode": c["status"],
            "title": c["title"],
            "ksc": c.get("ksc") or [],
            "cra": c.get("cra") or [],
            "osps": c.get("osps") or [],
        }
        if c["status"] == "auto":
            r = EVALUATORS[c["check"]](ev, c)
            entry.update(
                outcome=r["outcome"],
                result=r["result"],
                evidence=c["evidence"],
                data=r["data"],
            )
        else:
            entry.update(outcome="manual", result=c["evidence"], evidence=[], data={})
        controls.append(entry)
    summary = {o: sum(1 for c in controls if c["outcome"] == o) for o in OUTCOMES}
    return {
        "schema": SCHEMA,
        "kit_version": __version__,
        "generated_at": _now(),
        "repository": meta.get("repository", ""),
        "commit": meta.get("commit", ""),
        "ref": meta.get("ref", ""),
        "run_url": meta.get("run_url", ""),
        "tools": meta.get("tools", {}),
        "mapping": {"version": mapping.get("version"), "updated": mapping.get("updated")},
        "disclaimer": mapping["disclaimer"],
        "summary": summary,
        "controls": controls,
        "evidence_files": file_hashes(Path(evidence_dir)),
        "inputs_missing": ev.errors,
    }


