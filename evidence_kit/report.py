def _esc(text: Any) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _cite(ref: dict[str, Any], lang: str) -> str:
    return str(ref.get(f"cite_{lang}") or ref["cite"])


def _refs(ids: list[str], refs: dict[str, Any], lang: str) -> str:
    return "<br>".join(_esc(_cite(refs[i], lang)) for i in ids if i in refs) or "-"


def _ref_list(ids: list[str], refs: dict[str, Any], lang: str) -> str:
    return "; ".join(f"{_cite(refs[i], lang)}: {refs[i][lang]}" for i in ids if i in refs)


def render(doc: dict[str, Any], mapping: dict[str, Any], lang: str) -> str:
    t = T[lang]
    refs = mapping.get("references") or {}
    L: list[str] = []
    L.append(f"# {t['title']}")
    L.append("")
    L.append(f"> {doc['disclaimer'][lang].strip()}")
    L.append("")
    head = [
        (t["repo"], f"`{doc['repository']}`" if doc["repository"] else "-"),
        (t["commit"], f"`{doc['commit'][:12]}`" if doc["commit"] else "-"),
        (t["generated"], doc["generated_at"]),
        ("evidence-kit", f"{doc['kit_version']} (mapping {doc['mapping']['version']}, {doc['mapping']['updated']})"),
    ]
    if doc.get("run_url"):
        head.append((t["run"], doc["run_url"]))
    tools = {k: v for k, v in (doc.get("tools") or {}).items() if v}
    if tools:
        head.append((t["tools"], ", ".join(f"{k} {v}" for k, v in tools.items())))
    for k, v in head:
        L.append(f"- **{k}:** {v}")
    L.append("")

    # Summary
    L.append(f"## {t['summary']}")
    L.append("")
    L.append("| " + " | ".join(ICON[o] for o in OUTCOMES) + " |")
    L.append("|" + "---|" * len(OUTCOMES))
    L.append("| " + " | ".join(str(doc["summary"][o]) for o in OUTCOMES) + " |")
    L.append("")
    L.append(t["legend"])
    L.append("")
    L.append(t["not_proven"])
    L.append("")

    auto = [c for c in doc["controls"] if c["mode"] == "auto"]
    manual = [c for c in doc["controls"] if c["mode"] == "manual"]

    L.append(f"## {t['automated']}")
    L.append("")
    L.append(
        f"| {t['col_id']} | {t['col_control']} | {t['col_outcome']} | {t['col_result']} | "
        f"{t['col_ksc']} | {t['col_cra']} |"
    )
    L.append("|---|---|---|---|---|---|")
    for c in auto:
        L.append(
            f"| {c['id']} | {_esc(c['title'][lang])} | **{ICON[c['outcome']]}** | "
            f"{_esc(c['result'][lang])} | {_refs(c['ksc'], refs, lang)} | {_refs(c['cra'], refs, lang)} |"
        )
    L.append("")

    L.append(f"## {t['manual']}")
    L.append("")
    L.append(f"| {t['col_id']} | {t['col_control']} | {t['col_attach']} | {t['col_ksc']} | {t['col_cra']} |")
    L.append("|---|---|---|---|---|")
    for c in manual:
        L.append(
            f"| {c['id']} | {_esc(c['title'][lang])} | {_esc(c['result'][lang])} | "
            f"{_refs(c['ksc'], refs, lang)} | {_refs(c['cra'], refs, lang)} |"
        )
    L.append("")

    L.append(f"## {t['details']}")
    L.append("")
    for c in auto:
        L.append(f"### {c['id']}: {c['title'][lang]} ({ICON[c['outcome']]})")
        L.append("")
        L.append(c["result"][lang])
        L.append("")
        for key, label in (("ksc", "KSC"), ("cra", "CRA")):
            if c[key]:
                L.append(f"- **{label}:** {_ref_list(c[key], refs, lang)}")
        if c["osps"]:
            L.append(f"- **OSPS Baseline:** {', '.join(c['osps'])}")
        L.append(f"- **{t['evidence']}:** {', '.join(f'`{e}`' for e in c['evidence'])}")
        L.append("")
        L.extend(_detail_tables(c, t))
    L.append(f"## {t['files']}")
    L.append("")
    L.append(f"| {t['col_file']} | SHA-256 | {t['col_bytes']} |")
    L.append("|---|---|---|")
    for f in doc["evidence_files"]:
        L.append(f"| `{f['path']}` | `{f['sha256']}` | {f['bytes']} |")
    L.append("")

    L.append(f"## {t['sources']}")
    L.append("")
    for src in (mapping.get("sources") or {}).values():
        L.append(f"- {src['title'][lang]}: {src['url']}")
    L.append("")
    L.append("---")
    L.append("")
    L.append(t["help"])
    L.append("")
    L.append(t["footer"])
    L.append("")
    return "\n".join(L)


def _detail_tables(c: dict[str, Any], t: dict[str, str]) -> list[str]:
    d = c.get("data") or {}
    L: list[str] = []
    if c["id"] == "EK-VULN" and "by_severity" in d:
        L.append(f"| {t['col_sev']} | {t['col_count']} | {t['col_fixable']} |")
        L.append("|---|---|---|")
        for s in SEVERITIES:
            L.append(f"| {s} | {d['by_severity'][s]} | {d['fixable'][s]} |")
        L.append("")
        if d.get("top"):
            L.append(f"| ID | {t['col_sev']} | {t['col_pkg']} | {t['col_ver']} | {t['col_fixed']} |")
            L.append("|---|---|---|---|---|")
            for v in d["top"][:15]:
                L.append(
                    f"| {_esc(v['id'])} | {v['severity']} | {_esc(v['package'])} | "
                    f"{_esc(v['version'])} | {_esc(v['fixed']) or '-'} |"
                )
            L.append("")
    elif c["id"] == "EK-SCORECARD" and d.get("checks"):
        L.append(f"| {t['col_check']} | {t['col_score']} |")
        L.append("|---|---|")
        for ch in sorted(d["checks"], key=lambda x: (x["score"], x["name"])):
            score = ch["score"] if ch["score"] >= 0 else "n/a"
            L.append(f"| {_esc(ch['name'])} | {score} |")
        L.append("")
    elif c["id"] == "EK-SECRETS" and d.get("locations"):
        L.append(t["secrets_note"])
        L.append("")
        L.append(f"| {t['col_rule']} | {t['col_file']} | {t['col_line']} | Commit |")
        L.append("|---|---|---|---|")
        for loc in d["locations"]:
            L.append(f"| {_esc(loc['rule'])} | `{_esc(loc['file'])}` | {loc['line']} | `{loc['commit']}` |")
        L.append("")
    return L


def write(evidence_dir: Path, mapping: dict[str, Any], langs: list[str]) -> dict[str, Any]:
    evidence_dir = Path(evidence_dir)
    doc = build(evidence_dir, mapping)
    (evidence_dir / "evidence.json").write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    for lang in langs:
        (evidence_dir / REPORT_NAMES[lang]).write_text(render(doc, mapping, lang), encoding="utf-8")
    return doc
